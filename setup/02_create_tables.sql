-- LogSense AI: Table Definitions
-- Creates all tables required for the platform.

USE DATABASE KAFKA_LOGS;
USE SCHEMA RAW;

-- Central structured log store
CREATE TABLE IF NOT EXISTS PARSED_LOGS (
    LOG_ID NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOORDER,
    APP_NAME VARCHAR(256),
    TIMESTAMP VARCHAR(64),
    LOG_LEVEL VARCHAR(10),
    COMPONENT VARCHAR(256),
    MESSAGE VARCHAR(65535),
    SOURCE_FILE VARCHAR(512),
    INGESTED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

-- Staging table for Snowpipe automated ingestion
CREATE TABLE IF NOT EXISTS RAW_LOG_LANDING (
    RAW_LINE VARCHAR(65535),
    SOURCE_FILE VARCHAR(500),
    LOADED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
    PROCESSED BOOLEAN DEFAULT FALSE
);

-- Service Registry for business context enrichment
CREATE TABLE IF NOT EXISTS SERVICE_REGISTRY (
    SERVICE_NAME VARCHAR(16777216),
    TIER VARCHAR(16777216),
    TEAM_OWNER VARCHAR(16777216),
    BUSINESS_FUNCTION VARCHAR(16777216),
    AFFECTED_CUSTOMERS VARCHAR(16777216),
    LAST_DEPLOY_VERSION VARCHAR(16777216),
    LAST_DEPLOY_DATE TIMESTAMP_NTZ(9),
    JIRA_PROJECT_KEY VARCHAR(16777216),
    PAGERDUTY_SERVICE_ID VARCHAR(16777216)
);

-- Incident ticket management
CREATE TABLE IF NOT EXISTS INCIDENT_TICKETS (
    TICKET_ID NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOORDER,
    TITLE VARCHAR(16777216),
    DESCRIPTION VARCHAR(16777216),
    COMPONENT VARCHAR(16777216),
    APP_NAME VARCHAR(16777216),
    SEVERITY VARCHAR(16777216),
    PRIORITY VARCHAR(16777216),
    STATUS VARCHAR(16777216) DEFAULT 'Open',
    SEARCH_QUERY VARCHAR(16777216),
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

-- Audit trail for incident resolutions
CREATE TABLE IF NOT EXISTS AUDIT_RESOLUTIONS (
    RESOLUTION_ID NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1 NOORDER,
    TICKET_ID NUMBER(38,0),
    SEARCH_QUERY VARCHAR(16777216),
    DIAGNOSIS_SUMMARY VARCHAR(16777216),
    RESOLUTION_NOTES VARCHAR(16777216),
    COMPONENT VARCHAR(16777216),
    APP_NAME VARCHAR(16777216),
    RESOLVED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);
